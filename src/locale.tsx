export function LocaleProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = window.localStorage.getItem('mian-language')
    return saved === 'ur' ? 'ur' : 'en'
  })

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ur' ? 'rtl' : 'ltr'
    document.documentElement.dataset.language = language
    window.localStorage.setItem('mian-language', language)
  }, [language])

  const setLanguage = (nextLanguage: Language) => setLanguageState(nextLanguage)
  const t = (text: string) => {
    if (language === 'en') return text
    if (translations[text]) return translations[text]
    return Object.entries(translations)
      .filter(([source]) => source.length > 3 && text.includes(source))
      .sort(([first], [second]) => second.length - first.length)
      .reduce((translated, [source, replacement]) => {
        const escapedSource = source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        return translated.replace(new RegExp(`(?<![A-Za-z0-9])${escapedSource}(?![A-Za-z0-9])`, 'g'), replacement)
      }, text)
  }

  return <LocaleContext.Provider value={{ language, setLanguage, t }}>{children}</LocaleContext.Provider>
}

export function LocalizedContent({ children }: { children: ReactNode }) {
  const { t } = useLocale()

  function localize(node: ReactNode): ReactNode {
    if (typeof node === 'string') return t(node)
    if (Array.isArray(node)) return node.map(localize)
    if (!isValidElement<{ children?: ReactNode; [key: string]: unknown }>(node)) return node

    const { children: elementChildren, ...props } = node.props
    const localizedProps = { ...props }
    for (const attribute of ['aria-label', 'placeholder', 'title']) {
      const value = localizedProps[attribute]
      if (typeof value === 'string') localizedProps[attribute] = t(value)
    }

    return cloneElement(
      node,
      localizedProps,
      ...('children' in node.props ? [localize(elementChildren)] : []),
    )
  }

  return <>{localize(children)}</>
}
